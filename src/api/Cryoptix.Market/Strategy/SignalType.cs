        /// </summary>
        Sell = 2,
        /// <summary>
        /// Specifies the exit long value.
        /// </summary>
        ExitLong = 3,
        /// <summary>
        /// Specifies the exit short value.
        /// </summary>
        ExitShort = 4
    }
}
